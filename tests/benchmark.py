import os
import platform
import random
import statistics
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(ROOT, "src", "Python"))

import algorithms  
import validators as V  

SEED = 20260101
REPEATS = 5
BIG = 1_000_000_000
SIZES = [(10_000, 40_000), (50_000, 150_000), (100_000, 250_000)]


def timed(fn, request):
    t0 = time.perf_counter()
    out = fn(request)
    return time.perf_counter() - t0, out


def main():
    lines = []
    env = [
        "- Python: %s (%s)" % (platform.python_version(), platform.python_implementation()),
        "- OS: %s" % platform.platform(),
        "- CPU: %s" % (platform.processor() or "unknown"),
        "- Timer: time.perf_counter(); 1 warm-up call, %d timed calls per method and size; median reported" % REPEATS,
        "- Timed region: one call of algorithms.kruskal / algorithms.prim on an in-memory request (no generation, no JSON, no I/O)",
        "- Seed: random.Random(%d + size_index)" % SEED,
        "- Command: python tests/benchmark.py",
    ]
    lines += ["# Benchmark results (generated by `python tests/benchmark.py`)", ""] + env + [""]
    lines.append("| n | m | method | run times (s) | median (s) | cost |")
    lines.append("|---|---|--------|---------------|------------|------|")
    summary = []
    for idx, (n, m) in enumerate(SIZES):
        r = random.Random(SEED + idx)
        edges = [[r.randrange(n), r.randrange(n), r.randint(-BIG, BIG)] for _ in range(m)]
        results = {}
        for name in ("kruskal", "prim"):
            req = {"task": name, "n": n, "edges": edges}
            fn = getattr(algorithms, name)
            _, out = timed(fn, req)               
            errs = V.check_forest(req, out)         
            if errs:
                raise SystemExit("%s invalid on size %d: %s" % (name, n, errs))
            results[name] = out
            runs = [timed(fn, req)[0] for _ in range(REPEATS)]
            med = statistics.median(runs)
            summary.append((n, m, name, runs, med, out["cost"]))
            lines.append("| %d | %d | %s | %s | %.4f | %d |" % (
                n, m, name, ", ".join("%.4f" % x for x in runs), med, out["cost"]))
        if results["kruskal"]["cost"] != results["prim"]["cost"] or \
           results["kruskal"]["components"] != results["prim"]["components"]:
            raise SystemExit("Kruskal and Prim disagree on size %d" % n)
    lines += ["", "Both methods returned the same cost and component count on every size, and every forest passed `validators.check_forest`.", ""]
    ratios = []
    for i in range(0, len(summary), 2):
        k, p = summary[i], summary[i + 1]
        ratios.append("n=%d, m=%d: Prim/Kruskal median ratio = %.2f" % (k[0], k[1], p[4] / k[4]))
    lines += ["Median ratios:", ""] + ["- " + x for x in ratios] + [""]
    text = "\n".join(lines)
    with open(os.path.join(HERE, "benchmark_results.md"), "w", encoding="utf-8") as f:
        f.write(text)
    print(text)


if __name__ == "__main__":
    main()